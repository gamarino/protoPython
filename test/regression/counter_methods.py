# collections.Counter and deque iterators against CPython
# (counter_methods.expected is CPython's output).
from collections import Counter, deque

c = Counter("abracadabra")
print("most_common", c.most_common())
print("most_common 2", c.most_common(2))
print("most_common 0", c.most_common(0))
print("most_common big", c.most_common(10))
print("ints", Counter([3, 1, 3, 2, 3, 1]).most_common(2))
print("elements", sorted(c.elements()))
print("total", c.total())
print("missing", Counter()["x"])
print("repr", repr(Counter("aab")))
print("kw", sorted(Counter(a=3, b=1).items()))
print("mapping", sorted(Counter({"a": 2}).items()))
print("generator", sorted(Counter(x % 3 for x in range(10)).items()))
d = Counter("ab"); d.update("aaz"); print("update", sorted(d.items()))
d = Counter("ab"); d.update({"a": 5}); print("update mapping", sorted(d.items()))
d = Counter("ab"); d.subtract("aaz"); print("subtract", sorted(d.items()))
print("add", sorted((Counter("aab") + Counter("abc")).items()))
print("sub", sorted((Counter("aab") - Counter("abc")).items()))
print("or", sorted((Counter("aab") | Counter("abbc")).items()))
print("and", sorted((Counter("aab") & Counter("abbc")).items()))
print("pos", sorted((+Counter(a=1, b=-1)).items()))
print("neg", sorted((-Counter(a=1, b=-1)).items()))
print("eq", Counter(a=1) == Counter(a=1, b=0), Counter(a=1) <= Counter(a=2))
words = "the quick brown fox jumps over the lazy dog the end".split()
print("words", Counter(words).most_common(3))
big = Counter(i % 97 for i in range(5000))
print("big", big.most_common(3), len(big), big.total())

it = iter(deque([1, 2, 3]))
print("deque iter is self", iter(it) is it, list(it))
rit = reversed(deque([1, 2, 3]))
print("deque reversed is self", iter(rit) is rit, list(rit))
