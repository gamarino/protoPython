#!/usr/bin/env python3
"""Generate src/library/UnicodeNameTable.inc, the character-name table behind
`\\N{NAME}` escapes (src/library/UnicodeNames.cpp).

The names come from the running CPython's `unicodedata` (the Unicode version
CPython itself uses) and the aliases from the Unicode Character Database file
NameAliases.txt of the same version, so the table matches CPython's \\N exactly.

    python3 tools/gen_unicode_names.py /path/to/NameAliases.txt

Every name and alias written is checked with `unicodedata.lookup`.  The names
CPython derives by rule (HANGUL SYLLABLE ..., CJK UNIFIED IDEOGRAPH-XXXX) are
not stored: UnicodeNames.cpp computes them, and the table keeps only the code
point ranges that carry a `PREFIX-XXXX` name.

Format.  Each name is split at spaces into words; the words form a lexicon
ordered by frequency, and a name is stored as the sequence of its word
numbers (one byte below 192, two bytes otherwise).  An entry is
  [byte count][code point, 3 bytes big-endian; bit 23 = alias][word codes].
"""
import collections
import os
import re
import sys
import unicodedata

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, os.pardir, "src", "library", "UnicodeNameTable.inc")
ONE_BYTE = 192          # word numbers below this take one byte
RANGE_NAME = re.compile(r"(.*-)([0-9A-F]{4,6})$")


def collect(aliases_path):
    names = {}          # code point -> official name
    ranges = []         # [prefix, first, last] for PREFIX-XXXX names
    for cp in range(0x110000):
        n = unicodedata.name(chr(cp), None)
        if n is None:
            continue
        if n.startswith("HANGUL SYLLABLE "):
            continue    # computed (UnicodeNames.cpp)
        m = RANGE_NAME.match(n)
        if m and int(m.group(2), 16) == cp and m.group(2) == "%04X" % cp:
            if ranges and ranges[-1][0] == m.group(1) and ranges[-1][2] == cp - 1:
                ranges[-1][2] = cp
            else:
                ranges.append([m.group(1), cp, cp])
            continue
        names[cp] = n
    aliases = []
    with open(aliases_path, encoding="utf-8") as f:
        header = f.readline()
        for line in f:
            line = line.split("#", 1)[0].strip()
            if not line:
                continue
            cp_hex, alias, _kind = line.split(";")
            cp = int(cp_hex, 16)
            if unicodedata.lookup(alias) != chr(cp):
                sys.exit("alias %r does not resolve to U+%04X in this CPython" % (alias, cp))
            aliases.append((cp, alias))
    for cp, n in names.items():
        assert unicodedata.lookup(n) == chr(cp), n
    return names, ranges, aliases, header.strip("# \n")


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    names, ranges, aliases, aliases_version = collect(sys.argv[1])
    entries = sorted(names.items()) + [(cp | 0x800000, a) for cp, a in aliases]
    counts = collections.Counter(w for _, n in entries for w in n.split(" "))
    words = [w for w, _ in sorted(counts.items(), key=lambda kv: (-kv[1], kv[0]))]
    assert len(words) <= ONE_BYTE + 64 * 256
    number = {w: i for i, w in enumerate(words)}

    data = bytearray()
    for cp, n in entries:
        code = bytearray()
        for w in n.split(" "):
            i = number[w]
            if i < ONE_BYTE:
                code.append(i)
            else:
                i -= ONE_BYTE
                code += bytes((ONE_BYTE + (i >> 8), i & 0xFF))
        assert len(code) < 256
        data.append(len(code))
        data += bytes(((cp >> 16) & 0xFF, (cp >> 8) & 0xFF, cp & 0xFF))
        data += code

    lexicon = "".join(words).encode("ascii")
    offsets = [0]
    for w in words:
        offsets.append(offsets[-1] + len(w))
    by_spelling = sorted(range(len(words)), key=lambda i: words[i])
    prefixes = sorted({r[0] for r in ranges})

    def rows(values, per_line=24):
        values = list(values)
        return "\n".join(",".join(str(v) for v in values[i:i + per_line]) + ","
                         for i in range(0, len(values), per_line))

    with open(OUT, "w", encoding="ascii", newline="\n") as out:
        out.write("// Generated by tools/gen_unicode_names.py -- do not edit.\n")
        out.write("// Unicode %s (CPython %s unicodedata), aliases: %s.\n"
                  % (unicodedata.unidata_version, sys.version.split()[0], aliases_version))
        out.write("// %d names, %d aliases, %d words, %d name bytes.\n\n"
                  % (len(names), len(aliases), len(words), len(data)))
        out.write("static constexpr const char* kUnicodeVersion = \"%s\";\n" % unicodedata.unidata_version)
        out.write("static constexpr unsigned kOneByteWords = %d;\n" % ONE_BYTE)
        out.write("static constexpr unsigned kWordCount = %d;\n" % len(words))
        out.write("static const char kLexicon[] = {\n%s\n};\n" % rows(lexicon))
        out.write("static const uint32_t kLexiconOffsets[] = {\n%s\n};\n" % rows(offsets, 16))
        out.write("static const uint16_t kWordsBySpelling[] = {\n%s\n};\n" % rows(by_spelling, 16))
        out.write("static const unsigned char kNameData[] = {\n%s\n};\n" % rows(data))
        out.write("static const char* const kRangePrefixes[] = {\n%s\n};\n"
                  % "\n".join('    "%s",' % p for p in prefixes))
        out.write("struct NameRange { uint8_t prefix; uint32_t first, last; };\n")
        out.write("static const NameRange kNameRanges[] = {\n%s\n};\n"
                  % "\n".join("    {%d, 0x%X, 0x%X}," % (prefixes.index(p), a, b) for p, a, b in ranges))
    print("wrote", os.path.normpath(OUT), "-", len(names), "names,", len(aliases), "aliases,",
          len(ranges), "ranges,", len(data) + len(lexicon) + 4 * len(offsets) + 2 * len(words), "bytes")


if __name__ == "__main__":
    main()
